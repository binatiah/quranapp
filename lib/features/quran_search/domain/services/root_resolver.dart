import '../entities/root_candidate.dart';

/// واجهة خدمة تحديد واستخراج الجذور الصرفية (RootResolver Interface).
/// تطبق المستويات الستة الصارمة المحددة في وثيقة متطلبات المشروع (TRD):
/// 1. مطابقة كلمة منزوعة التشكيل (word_normalized).
/// 2. مطابقة أصل الكلمة (lemma_normalized).
/// 3. مطابقة الجذر المباشر إذا أدخل المستخدم جذرًا (root_normalized).
/// 4. البحث في القاموس المعجمي المحلي.
/// 5. التخمين الصرفي المنهجي (إزالة السوابق واللواحق مع التحقق من جدول الجذور).
/// 6. التخمين بالحروف المرتبة كخيار احتياطي أخير وتصنيفه صراحة كاقتراح غير مؤكد.
abstract interface class RootResolver {
  /// استخراج قائمة الجذور المرشحة لكلمة أو عبارة البحث مع درجة الثقة ونوع المطابقة
  Future<List<RootCandidate>> resolve(String query);
}
